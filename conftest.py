"""Root conftest: pytest loads this before parsing the command line.

Command-line options (pytest_addoption) must live here, not in tests/conftest.py.
Otherwise `pytest --trace-matrix traceability.md` fails with "unrecognized
arguments" when traceability.md already exists: pytest's early argument scan
takes the existing file for a test path in the repo root and never loads
tests/conftest.py before the option is parsed.
"""

import platform
import re
import shlex
from datetime import datetime
from pathlib import Path

import pytest

# --- Traceability matrix -----------------------------------------------------
# `pytest --trace-matrix traceability.md` writes a requirement -> test -> result
# table built from this run's actual outcomes and REQUIREMENTS.md.

REQ_ROW = re.compile(r"^\|\s*(REQ-\d+)\s*\|\s*(.*?)\s*\|")

_results = {}  # nodeid -> {"reqs": [...], "outcome": str, "props": [...]}


def pytest_addoption(parser):
    parser.addoption("--trace-matrix", metavar="PATH",
                     help="write a requirements traceability matrix (Markdown) to PATH")


@pytest.hookimpl(tryfirst=True)
def pytest_collection_modifyitems(items):
    # Runs before -k/-m deselection, so deselected tests show as "not run"
    # instead of making their requirement look untested.
    for item in items:
        _results[item.nodeid] = {
            "reqs": [m.args[0] for m in item.iter_markers("req")],
            "outcome": "not run",
            "props": [],
        }


@pytest.hookimpl(wrapper=True)
def pytest_runtest_makereport(item, call):
    report = yield
    entry = _results[item.nodeid]
    if report.failed and report.when != "call":
        entry["outcome"] = "error"  # fixture setup/teardown failed
    elif (report.when == "call" or report.skipped) and entry["outcome"] != "error":
        entry["outcome"] = report.outcome
    entry["props"] = list(item.user_properties)
    return report


def _requirement_status(outcomes):
    if not outcomes:
        return "**NO TEST**"
    if any(o in ("failed", "error") for o in outcomes):
        return "FAIL"
    if all(o == "passed" for o in outcomes):
        return "PASS"
    return "INCOMPLETE"  # some linked tests skipped or not run


def pytest_sessionfinish(session, exitstatus):
    path = session.config.getoption("--trace-matrix")
    if not path:
        return
    req_file = Path(session.config.rootpath) / "REQUIREMENTS.md"
    requirements = [m.groups() for line in req_file.read_text(encoding="utf-8").splitlines()
                    if (m := REQ_ROW.match(line))]
    known = {rid for rid, _ in requirements}

    lines = [
        "# Traceability Matrix",
        "",
        f"Generated by `pytest --trace-matrix` on {datetime.now():%Y-%m-%d %H:%M:%S}, "
        f"Python {platform.python_version()}, {platform.platform()}.",
        f"Command: `{shlex.join(['pytest', *session.config.invocation_params.args])}`",
        "",
        "| Requirement | Description | Linked tests | Result | Status |",
        "|---|---|---|---|---|",
    ]
    summary = {}
    for rid, text in requirements:
        linked = [(nid, r) for nid, r in _results.items() if rid in r["reqs"]]
        status = _requirement_status([r["outcome"] for _, r in linked])
        summary[status] = summary.get(status, 0) + 1
        tests = "<br>".join(f"`{nid}`" for nid, _ in linked) or "-"
        outcomes = "<br>".join(r["outcome"] for _, r in linked) or "-"
        lines.append(f"| {rid} | {text} | {tests} | {outcomes} | {status} |")

    lines += ["", "**Summary:** " + ", ".join(f"{k}: {v}" for k, v in sorted(summary.items()))]

    measured = [(nid, r) for nid, r in _results.items() if r["props"]]
    if measured:
        lines += ["", "## Measured values (this run)", "", "| Test | Metric | Value |", "|---|---|---|"]
        for nid, r in measured:
            for name, value in r["props"]:
                lines.append(f"| `{nid}` | {name} | {value} |")

    untraced = [nid for nid, r in _results.items() if not r["reqs"]]
    unknown = [(nid, rid) for nid, r in _results.items() for rid in r["reqs"] if rid not in known]
    lines += ["", "## Tests not linked to a requirement", ""]
    lines += [f"- `{nid}`" for nid in untraced] or ["None."]
    lines += ["", "## Tests tagged with an unknown requirement ID", ""]
    lines += [f"- `{nid}` -> {rid}" for nid, rid in unknown] or ["None."]

    Path(path).write_text("\n".join(lines) + "\n", encoding="utf-8")
